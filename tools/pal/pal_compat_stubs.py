#!/usr/bin/env python3
"""Generate the PAL compatibility shim for the port's hand-written sources.

The title sources in gta4-recomp/src were written against the USA executable and
reference ~840 generated functions by name. The PAL recompilation (see
pal_downgrade.py) contains most of them, but not all. Symbols that are missing
are declared and defined here as loud stubs, so the build links and any call
into a missing function is immediately visible in logcat instead of silently
doing nothing.

usage: pal_compat_stubs.py <generated dir> <src dir>
"""
import glob
import os
import re
import sys

# Also matches the __imp__sub_<addr> alias that DECLARE_REX_FUNC emits and that
# several hook call sites use directly (a leading \b would miss it because "_"
# is a word character). Also matches named symbols dropped from USA config.
EXTRA_NAMES = r"D3D_MemAllocAligned|CCommandBuffer_Destroy|D3DResource_Release"
IDENT = re.compile(rf"(?<![0-9A-Za-z])(?:__imp__)?(sub_[0-9A-F]{{8}}|{EXTRA_NAMES})\b")
DEF = re.compile(rf'extern\s+"C"\s+void\s+(sub_[0-9A-F]{{8}}|{EXTRA_NAMES})\s*\(')


def main() -> int:
    if len(sys.argv) != 3:
        return print(__doc__) or 2
    gen, src = sys.argv[1], sys.argv[2]

    declared = set(re.findall(r"DECLARE_REX_FUNC\((\w+)\)",
                              open(os.path.join(gen, "gta4_init.h"), encoding="utf-8").read()))
    sources = []
    for root, _, files in os.walk(src):
        sources += [os.path.join(root, name) for name in files
                    if name.endswith((".cpp", ".h", ".hpp", ".inc", ".inl"))
                    and name != "gta4_pal_stubs.cpp"]
    referenced, defined = set(), set()
    for path in sources:
        text = open(path, encoding="utf-8", errors="ignore").read()
        referenced |= set(IDENT.findall(text))
        defined |= set(DEF.findall(text))
        defined |= set(re.findall(r"DEFINE_REX_FUNC\((\w+)\)", text))

    # Every symbol the PAL init.h does not declare needs a declaration and a
    # stub definition. DEFINE_REX_FUNC defines `name` as a weak symbol that
    # tail-calls `__imp__name`, and defines `__imp__name`. If the port provides
    # a strong hook for `name`, the strong symbol overrides the weak one, and
    # the hook's call to `__imp__name` resolves to the stub below.
    undeclared = sorted(referenced - declared)
    stubs = undeclared
    print(f"referenced={len(referenced)} declared_in_pal={len(referenced & declared)} "
          f"defined_by_port={len(referenced & defined)} "
          f"compat_decls={len(undeclared)} stubs={len(stubs)}")

    header = ["// Generated by tools/pal_compat_stubs.py - PAL experiment shim.",
              "// Functions used by the title sources that the PAL recompilation",
              "// does not contain. Defined stubs abort if called; the rest are",
              "// implemented by the port itself (see gta4_pal_stubs.cpp).",
              ""]
    header += [f"DECLARE_REX_FUNC({name});" for name in undeclared]
    with open(os.path.join(gen, "gta4_pal_compat.h"), "w", encoding="utf-8", newline="") as f:
        f.write("\n".join(header) + "\n")

    body = ['// Generated by tools/pal_compat_stubs.py - PAL experiment shim.',
            '// Not part of the shipped port: only exists so the USA-oriented title',
            '// sources link against the PAL recompilation.',
            '#include "gta4_init.h"',
            '',
            '#include <cstdlib>',
            '#include <rex/logging.h>',
            '']
    for name in stubs:
        body += [
            f"DEFINE_REX_FUNC({name}) {{",
            "\tREX_FUNC_PROLOGUE();",
            f'\tREXLOG_ERROR("PAL compat: missing function {name} called");',
            "\tstd::abort();",
            "}",
            "",
        ]
    with open(os.path.join(src, "gta4_pal_stubs.cpp"), "w", encoding="utf-8", newline="") as f:
        f.write("\n".join(body))
    return 0


if __name__ == "__main__":
    sys.exit(main())
