#!/usr/bin/env python3
"""Re-target the USA-keyed gta4_config.toml to the PAL executable.

* [functions]: every "0xADDR" key is translated with the USA->PAL function map
  (tools/pal_match_functions.py). Entries without a confident match are
  dropped (rexglue discovers the function itself; a forced entry at a USA
  address would split an unrelated PAL function). Keys in KEEP_PAL are
  PAL-native and kept verbatim.
* [rexcrt]: replaced with PAL addresses verified by signature + caller count
  (see docs/05-log.md §21). memmove is intentionally left out: the PAL
  candidate could not be confirmed, so it stays recompiled guest code.

Usage: pal_remap_config.py <config.toml> <usa_to_pal.tsv> > new_config.toml
"""
import re
import sys

KEEP_PAL = {0x82518A40, 0x82A05828, 0x826EA240, 0x82154100, 0x829F6F10}
OK_METHODS = {"exact", "anchored"}

PAL_REXCRT = [
    ("memset",   0x8298EB40, "354 callers, stb fill + stw loop"),
    ("memcpy",   0x829907E0, "556 callers, std r3 / dcbt / ld-std copy"),
    ("_stricmp", 0x8298EFF0, "473 callers, case-folding compare"),
    ("strncmp",  0x8298FFD0, "111 callers, subfc. + bdnzf"),
    ("strncpy",  0x8298FEA0, "100 callers, copy + null pad"),
    ("strchr",   0x8298FE60, " 33 callers, lbz/cmpwi/cmpw/lbzu"),
    ("strrchr",  0x82991550, " 30 callers, forward scan keeps last match"),
    ("strstr",   0x8298EDD0, " 24 callers, nested byte compare"),
]

KEY = re.compile(r'^"0x([0-9A-Fa-f]{8})"(\s*=.*)$')


def main():
    cfg, tsv = sys.argv[1], sys.argv[2]
    m = {}
    for line in open(tsv).read().splitlines()[1:]:
        u, p, meth, _ = line.split("\t")
        if meth in OK_METHODS:
            m[int(u, 16)] = int(p, 16)

    out, section = [], None
    kept = mapped = dropped = 0
    seen = set()
    crt_done = False
    for line in open(cfg):
        s = line.rstrip("\n")
        sec = re.match(r"^\[(\w+)\]", s)
        if sec:
            section = sec.group(1)
            out.append(s)
            if section == "rexcrt":
                out.append("# PAL (0.0.0.6) addresses - generated by tools/pal_remap_config.py")
                for n, a, c in PAL_REXCRT:
                    out.append(f"{n:<8} = 0x{a:08X}   # {c}")
                out.append("# memmove: not remapped (PAL candidate unconfirmed) -> stays guest code")
                crt_done = True
            continue
        if section == "rexcrt":
            if s.startswith("#") or not s.strip():
                if not s.strip():
                    out.append(s)
                continue
            continue  # drop USA rexcrt entries
        k = KEY.match(s)
        if section == "functions" and k:
            a = int(k.group(1), 16)
            if a in KEEP_PAL:
                na = a; kept += 1
            elif a in m:
                na = m[a]; mapped += 1
            else:
                dropped += 1
                continue
            if na in seen:
                continue
            seen.add(na)
            rest = k.group(2)
            if na != a:
                rest = re.sub(r"\s*#.*$", "", rest) + f"   # USA 0x{a:08X}"
            out.append(f'"0x{na:08X}"{rest}')
            continue
        out.append(s)
    assert crt_done, "no [rexcrt] section"
    print("\n".join(out))
    print(f"# remap: kept={kept} mapped={mapped} dropped={dropped}", file=sys.stderr)


if __name__ == "__main__":
    main()
